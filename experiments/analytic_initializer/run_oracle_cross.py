"""Paired oracle cross experiment for the grey-start failure attribution.

The two arms differ in exactly one reduced field:

``grey_T_truth_m``
    Eddington-grey temperature with the corpus column mass.
``truth_T_grey_m``
    Corpus temperature with the constant-opacity grey column mass.

Both arms are passed through the Paper-II ``(m,T)`` reconstruction
(``reduced_state.reconstruct``); pressure, populations, opacity, and transfer
are generated by the same certified bridge. The unchanged 15-iteration
production solver is then identical.
This is a diagnostic experiment, not a production initializer or a sealed
evaluation.  It is deliberately small so a failure can stop the next,
more expensive physical-ODE stage before any tuning begins.
"""

